-- Run once in Oracle Database Actions while logged in as INTERNMATE.
-- This links each project to the mentor responsible for it.

CREATE TABLE INTERNMATE.OPERATIONS_MENTORPROJECTASSIGNMENT (
    ID NUMBER(19) GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    CREATED_AT TIMESTAMP(6) NOT NULL,
    UPDATED_AT TIMESTAMP(6) NOT NULL,
    MENTOR_ID NUMBER(19) NOT NULL,
    PROJECT_ID NUMBER(19) NOT NULL,
    UNIQUE (MENTOR_ID, PROJECT_ID),
    FOREIGN KEY (MENTOR_ID) REFERENCES INTERNMATE.AUTH_USER(ID),
    FOREIGN KEY (PROJECT_ID) REFERENCES INTERNMATE.OPERATIONS_PROJECT(ID) ON DELETE CASCADE
);

CREATE INDEX INTERNMATE.IX_OMPA_PROJECT
    ON INTERNMATE.OPERATIONS_MENTORPROJECTASSIGNMENT(PROJECT_ID);

COMMIT;
